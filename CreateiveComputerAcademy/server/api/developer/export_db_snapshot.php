<?php
@set_time_limit(300);
@ini_set('memory_limit', '512M');

require_once '../../config/cors.php';
require_once '../../config/database.php';
require_once __DIR__ . '/developer_guard.php';

$database = new Database();
$db = $database->getConnection();

$data = json_decode(file_get_contents("php://input"), true) ?? [];
$token = $data['token'] ?? ($_SERVER['HTTP_AUTHORIZATION'] ?? ($_GET['token'] ?? ''));
if (strpos($token, 'Bearer ') === 0) {
    $token = substr($token, 7);
}

$devUser = verifyDeveloperAccess($db, $token);
if (!$devUser) {
    http_response_code(403);
    echo json_encode(["status" => "error", "message" => "Forbidden: Developer or Admin access required."]);
    exit;
}

$format = $_GET['format'] ?? ($data['format'] ?? 'download');

try {
    // 1. Fetch all tables
    $tableStmt = $db->query("SHOW FULL TABLES WHERE Table_type = 'BASE TABLE'");
    $tables = $tableStmt->fetchAll(PDO::FETCH_COLUMN);

    $dbName = $db->query("SELECT DATABASE()")->fetchColumn();
    $now = date('Y-m-d H:i:s');

    $sql = "-- ========================================================\n";
    $sql .= "-- CCA Database Snapshot & Disaster Recovery Dump\n";
    $sql .= "-- Database: {$dbName}\n";
    $sql .= "-- Generated: {$now} (Asia/Dhaka)\n";
    $sql .= "-- Generated by Developer: {$devUser['name']} (ID: {$devUser['id']})\n";
    $sql .= "-- Total Tables: " . count($tables) . "\n";
    $sql .= "-- ========================================================\n\n";
    $sql .= "SET FOREIGN_KEY_CHECKS=0;\n";
    $sql .= "SET SQL_MODE = \"NO_AUTO_VALUE_ON_ZERO\";\n";
    $sql .= "SET time_zone = \"+06:00\";\n\n";

    $totalRows = 0;

    foreach ($tables as $table) {
        // Skip log tables if too large or dump everything
        $sql .= "-- --------------------------------------------------------\n";
        $sql .= "-- Structure for table `{$table}`\n";
        $sql .= "-- --------------------------------------------------------\n";
        $sql .= "DROP TABLE IF EXISTS `{$table}`;\n";

        $createStmt = $db->query("SHOW CREATE TABLE `{$table}`");
        $createRow = $createStmt->fetch(PDO::FETCH_NUM);
        $sql .= $createRow[1] . ";\n\n";

        // Table Data
        $dataStmt = $db->query("SELECT * FROM `{$table}`");
        $rows = $dataStmt->fetchAll(PDO::FETCH_ASSOC);
        $rowCount = count($rows);
        $totalRows += $rowCount;

        if ($rowCount > 0) {
            $sql .= "-- Dumping data for table `{$table}` ({$rowCount} rows)\n";

            $columns = array_keys($rows[0]);
            $colList = '`' . implode('`, `', $columns) . '`';

            $chunkSize = 100;
            $chunks = array_chunk($rows, $chunkSize);

            foreach ($chunks as $chunk) {
                $sql .= "INSERT INTO `{$table}` ({$colList}) VALUES\n";
                $rowStrings = [];
                foreach ($chunk as $row) {
                    $vals = [];
                    foreach ($columns as $col) {
                        $v = $row[$col];
                        if (is_null($v)) {
                            $vals[] = "NULL";
                        } elseif (is_numeric($v)) {
                            $vals[] = $v;
                        } else {
                            $vals[] = $db->quote($v);
                        }
                    }
                    $rowStrings[] = "(" . implode(", ", $vals) . ")";
                }
                $sql .= implode(",\n", $rowStrings) . ";\n";
            }
            $sql .= "\n";
        }
    }

    $sql .= "SET FOREIGN_KEY_CHECKS=1;\n";
    $sql .= "-- Dump completed at: " . date('Y-m-d H:i:s') . "\n";

    $filenameBase = "cca_db_snapshot_" . date('Y_m_d_His');
    $compressed = function_exists('gzencode') ? gzencode($sql, 9) : null;

    // Save a persistent backup copy in server/backups
    $backupDir = dirname(__DIR__, 2) . '/backups';
    if (!file_exists($backupDir)) {
        @mkdir($backupDir, 0755, true);
        @file_put_contents($backupDir . '/.htaccess', "Deny from all\n");
    }

    $savedFilePath = $backupDir . '/' . ($compressed ? "{$filenameBase}.sql.gz" : "{$filenameBase}.sql");
    @file_put_contents($savedFilePath, $compressed ? $compressed : $sql);

    // If direct stream download requested
    if ($format === 'download') {
        header("Access-Control-Expose-Headers: Content-Disposition");
        if ($compressed) {
            header('Content-Type: application/x-gzip');
            header('Content-Disposition: attachment; filename="' . $filenameBase . '.sql.gz"');
            header('Content-Length: ' . strlen($compressed));
            echo $compressed;
        } else {
            header('Content-Type: application/sql');
            header('Content-Disposition: attachment; filename="' . $filenameBase . '.sql"');
            header('Content-Length: ' . strlen($sql));
            echo $sql;
        }
        exit;
    }

    // JSON response mode
    $fileSizeBytes = $compressed ? strlen($compressed) : strlen($sql);
    $sizeFormatted = $fileSizeBytes > 1048576 ? round($fileSizeBytes / 1048576, 2) . ' MB' : round($fileSizeBytes / 1024, 2) . ' KB';

    echo json_encode([
        "status" => "success",
        "message" => "Database snapshot generated successfully.",
        "filename" => $compressed ? "{$filenameBase}.sql.gz" : "{$filenameBase}.sql",
        "size_bytes" => $fileSizeBytes,
        "size_formatted" => $sizeFormatted,
        "total_tables" => count($tables),
        "total_rows" => $totalRows,
        "database" => $dbName,
        "generated_at" => $now
    ]);

} catch (Exception $e) {
    http_response_code(500);
    echo json_encode(["status" => "error", "message" => "Snapshot generation failed: " . $e->getMessage()]);
}
?>
