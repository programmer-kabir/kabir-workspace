<?php
@set_time_limit(300);
@ini_set('memory_limit', '512M');

// Start clean output buffering so we can catch any unintended errors
ob_start();

require_once '../../config/cors.php';
require_once '../../config/database.php';
require_once __DIR__ . '/developer_guard.php';

$database = new Database();
$db = $database->getConnection();

$data = json_decode(file_get_contents("php://input"), true) ?? [];
$token = $data['token'] ?? ($_SERVER['HTTP_AUTHORIZATION'] ?? ($_GET['token'] ?? ''));
if (strpos($token, 'Bearer ') === 0) {
    $token = substr($token, 7);
}

$devUser = verifyDeveloperAccess($db, $token);
if (!$devUser) {
    ob_end_clean();
    http_response_code(403);
    echo json_encode(["status" => "error", "message" => "Forbidden: Developer or Admin access required."]);
    exit;
}

if (!class_exists('ZipArchive')) {
    ob_end_clean();
    http_response_code(500);
    echo json_encode([
        "status" => "error",
        "message" => "PHP ZipArchive extension is not enabled on this server."
    ]);
    exit;
}

try {
    $dbName = $db->query("SELECT DATABASE()")->fetchColumn();
    $now = date('Y-m-d H:i:s');
    $dateStamp = date('Y_m_d_His');

    // ── 1. GENERATE COMPLETE DATABASE SQL DUMP ──────────────────────────────
    $tableStmt = $db->query("SHOW FULL TABLES WHERE Table_type = 'BASE TABLE'");
    $tables = $tableStmt->fetchAll(PDO::FETCH_COLUMN);

    $sql = "-- ========================================================\n";
    $sql .= "-- CCA FULL SYSTEM DISASTER RECOVERY: DATABASE DUMP\n";
    $sql .= "-- Database: {$dbName}\n";
    $sql .= "-- Generated: {$now} (Asia/Dhaka)\n";
    $sql .= "-- Generated By: {$devUser['name']} (ID: {$devUser['id']})\n";
    $sql .= "-- Total Tables: " . count($tables) . "\n";
    $sql .= "-- ========================================================\n\n";
    $sql .= "SET FOREIGN_KEY_CHECKS=0;\n";
    $sql .= "SET SQL_MODE = \"NO_AUTO_VALUE_ON_ZERO\";\n";
    $sql .= "SET time_zone = \"+06:00\";\n\n";

    $totalRows = 0;
    foreach ($tables as $table) {
        $sql .= "-- --------------------------------------------------------\n";
        $sql .= "-- Structure for table `{$table}`\n";
        $sql .= "-- --------------------------------------------------------\n";
        $sql .= "DROP TABLE IF EXISTS `{$table}`;\n";

        $createStmt = $db->query("SHOW CREATE TABLE `{$table}`");
        $createRow = $createStmt->fetch(PDO::FETCH_NUM);
        $sql .= $createRow[1] . ";\n\n";

        $dataStmt = $db->query("SELECT * FROM `{$table}`");
        $rows = $dataStmt->fetchAll(PDO::FETCH_ASSOC);
        $rowCount = count($rows);
        $totalRows += $rowCount;

        if ($rowCount > 0) {
            $sql .= "-- Dumping data for table `{$table}` ({$rowCount} rows)\n";
            $columns = array_keys($rows[0]);
            $colList = '`' . implode('`, `', $columns) . '`';
            $chunks = array_chunk($rows, 100);

            foreach ($chunks as $chunk) {
                $sql .= "INSERT INTO `{$table}` ({$colList}) VALUES\n";
                $rowStrings = [];
                foreach ($chunk as $row) {
                    $vals = [];
                    foreach ($columns as $col) {
                        $v = $row[$col];
                        if (is_null($v)) {
                            $vals[] = "NULL";
                        } elseif (is_numeric($v)) {
                            $vals[] = $v;
                        } else {
                            $vals[] = $db->quote($v);
                        }
                    }
                    $rowStrings[] = "(" . implode(", ", $vals) . ")";
                }
                $sql .= implode(",\n", $rowStrings) . ";\n";
            }
            $sql .= "\n";
        }
    }
    $sql .= "SET FOREIGN_KEY_CHECKS=1;\n";
    $sql .= "-- Full Dump completed at: {$now}\n";

    // ── 2. CREATE ZIP ARCHIVE WITH PHP CODEBASE + SQL DUMP ───────────────────
    $serverRoot = dirname(__DIR__, 2); // path to /server
    $backupDir = $serverRoot . '/backups';
    
    // Check if backups dir is writable, else use sys_get_temp_dir()
    $canUseBackupDir = false;
    if (!file_exists($backupDir)) {
        @mkdir($backupDir, 0755, true);
    }
    if (file_exists($backupDir) && is_writable($backupDir)) {
        $canUseBackupDir = true;
        @file_put_contents($backupDir . '/.htaccess', "Deny from all\n");
    }

    $zipFilename = "cca_full_system_php_and_db_{$dateStamp}.zip";
    $zipFilePath = $canUseBackupDir 
        ? ($backupDir . '/' . $zipFilename) 
        : (sys_get_temp_dir() . '/' . $zipFilename);

    $zip = new ZipArchive();
    $openRes = $zip->open($zipFilePath, ZipArchive::CREATE | ZipArchive::OVERWRITE);
    if ($openRes !== true) {
        throw new Exception("Unable to create zip archive (Code: {$openRes}) at {$zipFilePath}");
    }

    // Add Database Dump directly into the ZIP
    $zip->addFromString("DATABASE_BACKUP/database_dump_{$dateStamp}.sql", $sql);

    // Add Restore Instructions Readme
    $restoreGuide = "# CCA FULL SYSTEM DISASTER RECOVERY ARCHIVE\n\n";
    $restoreGuide .= "Generated: {$now} (Asia/Dhaka)\n";
    $restoreGuide .= "Author: {$devUser['name']}\n";
    $restoreGuide .= "Database: {$dbName} (" . count($tables) . " tables, {$totalRows} rows)\n\n";
    $restoreGuide .= "## RESTORATION STEPS:\n";
    $restoreGuide .= "1. Extract the contents of this ZIP archive into your web server's `/server` directory.\n";
    $restoreGuide .= "2. Open phpMyAdmin or your MySQL command line.\n";
    $restoreGuide .= "3. Import `DATABASE_BACKUP/database_dump_{$dateStamp}.sql` into your database.\n";
    $restoreGuide .= "4. Check `config/database.php` to ensure DB credentials match your new server.\n";
    $restoreGuide .= "5. Done! Your entire Creative Computer Academy system is 100% restored.\n";
    $zip->addFromString("RESTORE_INSTRUCTIONS.md", $restoreGuide);

    // Target specific codebase folders only to avoid scanning large or unreadable files
    $targetFolders = ['api', 'config', 'data'];
    $addedFilesCount = 0;

    foreach ($targetFolders as $folderName) {
        $folderPath = $serverRoot . '/' . $folderName;
        if (!is_dir($folderPath)) continue;

        $iterator = new RecursiveIteratorIterator(
            new RecursiveDirectoryIterator($folderPath, RecursiveDirectoryIterator::SKIP_DOTS),
            RecursiveIteratorIterator::SELF_FIRST
        );

        foreach ($iterator as $item) {
            if ($item->isDir()) {
                $rel = str_replace('\\', '/', substr($item->getRealPath(), strlen($serverRoot) + 1));
                $zip->addEmptyDir("server/" . $rel);
            } else if ($item->isFile()) {
                $realPath = $item->getRealPath();
                if (!$realPath || !is_readable($realPath)) continue;

                // Skip large binary files or archives
                $fsize = @filesize($realPath);
                if ($fsize === false || $fsize > 12 * 1024 * 1024) continue;

                $ext = strtolower(pathinfo($realPath, PATHINFO_EXTENSION));
                if (in_array($ext, ['sql', 'gz', 'zip', 'tar', 'log', 'mp4', 'avi'])) continue;

                $rel = str_replace('\\', '/', substr($realPath, strlen($serverRoot) + 1));
                if ($zip->addFile($realPath, "server/" . $rel)) {
                    $addedFilesCount++;
                }
            }
        }
    }

    // Add root server files
    $rootFiles = ['.htaccess', '.env.example', 'index.php'];
    foreach ($rootFiles as $rf) {
        $rfPath = $serverRoot . '/' . $rf;
        if (file_exists($rfPath) && is_readable($rfPath)) {
            $zip->addFile($rfPath, "server/" . $rf);
            $addedFilesCount++;
        }
    }

    $closeOk = $zip->close();
    if (!$closeOk || !file_exists($zipFilePath)) {
        throw new Exception("ZipArchive failed to finalize archive. Added {$addedFilesCount} files.");
    }

    clearstatcache(true, $zipFilePath);
    $zipSize = filesize($zipFilePath);
    if (!$zipSize || $zipSize === 0) {
        throw new Exception("Generated ZIP file is 0 bytes.");
    }

    // ── 3. CLEAN BUFFERS & STREAM DOWNLOAD TO BROWSER ────────────────────────
    while (ob_get_level() > 0) {
        ob_end_clean();
    }

    $origin = $_SERVER['HTTP_ORIGIN'] ?? '';
    if (!empty($origin)) {
        header("Access-Control-Allow-Origin: " . $origin);
    }
    header("Access-Control-Allow-Methods: GET, POST, OPTIONS");
    header("Access-Control-Allow-Headers: Content-Type, Authorization, X-Requested-With");
    header("Access-Control-Expose-Headers: Content-Disposition, Content-Length");

    header('Content-Type: application/zip', true);
    header('Content-Disposition: attachment; filename="' . $zipFilename . '"');
    header('Content-Length: ' . $zipSize);
    header('Cache-Control: no-cache, no-store, must-revalidate');
    header('Pragma: no-cache');
    header('Expires: 0');

    // Stream file safely in 64KB chunks
    $fp = fopen($zipFilePath, 'rb');
    if ($fp) {
        while (!feof($fp)) {
            echo fread($fp, 65536);
            flush();
        }
        fclose($fp);
    } else {
        readfile($zipFilePath);
    }
    exit;

} catch (Exception $e) {
    while (ob_get_level() > 0) {
        ob_end_clean();
    }
    http_response_code(500);
    echo json_encode([
        "status" => "error",
        "message" => "Full system backup failed: " . $e->getMessage()
    ]);
}
?>
