const HomeGreeting = ({ userName }) => {
  const [displayText, setDisplayText] = useState("");

  const hour = new Date().getHours();

  let greeting = "";
  let greetingIcon = "";

  if (hour >= 5 && hour < 12) {
    greeting = "শুভ সকাল";
    greetingIcon = "🌅";
  } else if (hour >= 12 && hour < 17) {
    greeting = "শুভ দুপুর";
    greetingIcon = "☀️";
  } else if (hour >= 17 && hour < 21) {
    greeting = "শুভ সন্ধ্যা";
    greetingIcon = "🌆";
  } else {
    greeting = "শুভ রাত্রি";
    greetingIcon = "🌙";
  }

 useEffect(() => {
  let typingInterval;
  let timeout;

  const startTyping = () => {

    // random wish
    const randomWish =
      wishes[Math.floor(Math.random() * wishes.length)];

    let charIndex = 0;
    let currentText = "";

    typingInterval = setInterval(() => {

      currentText += randomWish.charAt(charIndex);

      setDisplayText(currentText);

      charIndex++;

      // typing finished
      if (charIndex >= randomWish.length) {

        clearInterval(typingInterval);

        timeout = setTimeout(() => {
          setDisplayText("");
          startTyping();
        }, 2500);

      }

    }, 45);
  };

  startTyping();

  return () => {
    clearInterval(typingInterval);
    clearTimeout(timeout);
  };
}, []);
  return (
    <div className="relative mb-6 overflow-hidden rounded-3xl border border-indigo-100 bg-gradient-to-r from-indigo-50 via-white to-blue-50 p-6 shadow-sm transition-all duration-300 hover:shadow-lg">

      {/* glow effect */}
      <div className="absolute -right-10 -top-10 h-40 w-40 rounded-full bg-indigo-100 blur-3xl opacity-40"></div>

      <div className="relative flex items-start gap-4">

        {/* icon */}
        <div className="flex h-14 w-14 items-center justify-center rounded-2xl bg-gradient-to-br from-indigo-500 to-blue-500 text-2xl text-white shadow-lg">
          {greetingIcon}
        </div>

        {/* text */}
        <div className="flex-1">

          <h1 className="text-2xl font-bold text-slate-800">
            {greeting}{" "}
            <span className="text-indigo-600">
              {userName}
            </span>
          </h1>

          <div className="mt-2 flex items-center gap-2">

            <span className="text-sm leading-relaxed text-slate-600">
              {displayText}
            </span>

            {/* blinking cursor */}
            <span className="h-4 w-[2px] animate-pulse bg-indigo-500"></span>

          </div>

        </div>
      </div>
    </div>
  );
};

export default HomeGreeting;