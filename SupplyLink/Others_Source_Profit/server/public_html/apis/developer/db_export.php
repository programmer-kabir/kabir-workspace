<?php
// =========================================================================
// SupplyLink - Full Database SQL Dump & Backup Exporter
// Restricted strictly to Admin and Developer
// =========================================================================

ini_set('memory_limit', '512M');
set_time_limit(600);

require_once __DIR__ . '/../cors.php';
require_once __DIR__ . '/../auth_guard.php';
guardAdminDevOnly();

require_once __DIR__ . '/../db.php';

$dbName = 'supplylink';
// Detect active DB name from connection
$dbRes = $mysqli->query("SELECT DATABASE() AS current_db");
if ($dbRes && $row = $dbRes->fetch_assoc()) {
    if (!empty($row['current_db'])) {
        $dbName = $row['current_db'];
    }
}

$filename = "supplylink_db_backup_" . date("Y-m-d_H-i-s") . ".sql";

// Check if download stream is requested
header("Content-Type: application/sql; charset=UTF-8");
header("Content-Disposition: attachment; filename=\"{$filename}\"");
header("Pragma: no-cache");
header("Expires: 0");

$out = fopen("php://output", "w");

fwrite($out, "-- ========================================================\n");
fwrite($out, "-- SupplyLink Complete Database Backup\n");
fwrite($out, "-- Database: {$dbName}\n");
fwrite($out, "-- Date: " . date("Y-m-d H:i:s") . "\n");
fwrite($out, "-- Generated by: " . ($_SESSION['user']['name'] ?? 'Admin/Dev') . " (ID: " . ($_SESSION['user']['id'] ?? 'N/A') . ")\n");
fwrite($out, "-- ========================================================\n\n");

fwrite($out, "SET FOREIGN_KEY_CHECKS=0;\n");
fwrite($out, "SET SQL_MODE = \"NO_AUTO_VALUE_ON_ZERO\";\n");
fwrite($out, "SET time_zone = \"+06:00\";\n");
fwrite($out, "SET NAMES utf8mb4;\n\n");

// Get all tables
$tables = [];
$res = $mysqli->query("SHOW TABLES");
if ($res) {
    while ($row = $res->fetch_row()) {
        $tables[] = $row[0];
    }
}

foreach ($tables as $table) {
    fwrite($out, "\n-- --------------------------------------------------------\n");
    fwrite($out, "-- Table structure for table `{$table}`\n");
    fwrite($out, "-- --------------------------------------------------------\n\n");
    fwrite($out, "DROP TABLE IF EXISTS `{$table}`;\n");

    $createRes = $mysqli->query("SHOW CREATE TABLE `{$table}`");
    if ($createRes && $createRow = $createRes->fetch_row()) {
        fwrite($out, $createRow[1] . ";\n\n");
    }

    // Dump Data
    fwrite($out, "-- Dumping data for table `{$table}`\n");
    $dataRes = $mysqli->query("SELECT * FROM `{$table}`");
    if ($dataRes && $dataRes->num_rows > 0) {
        $numFields = $dataRes->field_count;

        $batchCount = 0;
        $batchValues = [];

        while ($row = $dataRes->fetch_row()) {
            $vals = [];
            for ($i = 0; $i < $numFields; $i++) {
                if (is_null($row[$i])) {
                    $vals[] = "NULL";
                } elseif (is_numeric($row[$i])) {
                    $vals[] = $row[$i];
                } else {
                    $vals[] = "'" . $mysqli->real_escape_string($row[$i]) . "'";
                }
            }
            $batchValues[] = "(" . implode(", ", $vals) . ")";
            $batchCount++;

            // Output in batches of 100 rows to optimize memory and SQL size
            if ($batchCount >= 100) {
                fwrite($out, "INSERT INTO `{$table}` VALUES\n" . implode(",\n", $batchValues) . ";\n");
                $batchValues = [];
                $batchCount = 0;
            }
        }

        if (!empty($batchValues)) {
            fwrite($out, "INSERT INTO `{$table}` VALUES\n" . implode(",\n", $batchValues) . ";\n");
        }
    }
    fwrite($out, "\n");
}

fwrite($out, "SET FOREIGN_KEY_CHECKS=1;\n");
fwrite($out, "-- Backup completed successfully.\n");
fclose($out);
exit;
